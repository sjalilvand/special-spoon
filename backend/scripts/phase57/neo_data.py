def facet_of(i: int) -> str:
    """نام زیرمقیاس فارسی گویه i (1-based) — مطابق آرایش چرخه‌ای رسمی فرم."""
    di = (i - 1) % 5
    fi = ((i - 1) // 5) % 6
    dom, facs = FACET_NAMES[di]
    return f"{facs[fi]} ({dom})"