def build_mmpi(rng: random.Random) -> dict:
    questions: list[dict] = []
    for key, name, count, stems in MMPI_SCALES:
        texts = expand(stems, MMPI_PREFIX, count)
        # حدود یک‌چهارم گویه‌ها معکوس‌کلید (مطابق سبک ابزار واقعی)
        for i, text in enumerate(texts):
            rev = (i % 4 == 3) if key in ("L", "K", "Mf") else (i % 6 == 5)
            questions.append(q(text + ".", TF_R if rev else TF, subscale=name))
    rng.shuffle(questions)
    total_max = len(questions)  # هر گویه حداکثر ۱
    interps = bands(total_max, [
        (0.0, 0.34, "بیش‌نمایی پایین (روایی)", "پاسخ‌دهی بسیار سخت‌گیرانه؛ احتمال کم‌نمایی مشکلات. تفسیر بالینی نیاز به گفت‌وگوی تخصصی دارد."),
        (0.34, 0.55, "نمایه بالینی مرزی", "در برخی مقیاس‌ها ارتقای خفیف دیده می‌شود؛ بررسی در جلسه مشاوره توصیه می‌شود."),
        (0.55, 0.75, "نمایه بالینی مرتفع", "الگوهای مختل‌کننده شخصیتی/خلقی مشخص است؛ مشاوره حرفه‌ای و پروتکل درمانی پیشنهاد می‌شود."),
        (0.75, 1.0, "نمایه بالینی بسیار مرتفع", "شکایت‌های چندگانه و شدید؛ ارزیابی جامع بالینی و مداخله فوری اولویت دارد."),
    ])
    return test(
        "mmpi-sf-370", "MMPI-SF-370", "آزمون شخصیت چندوجهی مینه‌سوتا",
        "Minnesota Multiphasic Personality Inventory",
        "جامع‌ترین ابزار سنجش شخصیت و آسیب‌شناسی روانی با ۳۷۰ گویه درست/نادرست در ۱۳ مقیاس روایی و بالینی؛ برای بزرگسالان بالای ۱۶ سال.",
        "فردی", "بالای ۱۶ سال", 50, "#ec4899", 1, "published",
        questions, interps,
    )


