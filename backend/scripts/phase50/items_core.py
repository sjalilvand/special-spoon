def build_mcmi(rng: random.Random) -> dict:
    questions: list[dict] = []
    for name, count, stems in MCMI_SCALES:
        texts = expand(stems, MCMI_PREFIX, count)
        for i, text in enumerate(texts):
            rev = (i % 7 == 6)
            questions.append(q(text + ".", TF_R if rev else TF, subscale=name))
    rng.shuffle(questions)
    total_max = len(questions)
    interps = bands(total_max, [
        (0.0, 0.4, "الگوی شخصیتی نرمال", "پاسخ‌ها در محدوده الگوهای سازگارانه است؛ نیازی به مداخله نیست."),
        (0.4, 0.6, "سندروم بالینی مرزی", "برخی الگوها برجسته است؛ گفت‌وگوی تخصصی برای تفسیر دقیق پیشنهاد می‌شود."),
        (0.6, 0.8, "الگوی بالینی برجسته", "حضور میلون: الگوهای شخصیتی/سندروم‌ها در آستانه بالینی است؛ مشاوره حرفه‌ای لازم است."),
        (0.8, 1.0, "الگوی بالینی شدید", "نمایه‌های شدید؛ ارزیابی جامع و برنامه درمان فعال توصیه می‌شود."),
    ])
    return test(
        "mcmi-iii-175", "MCMI-III-175", "آزمون بالینی چندمحوری میلون ۳",
        "Millon Clinical Multiaxial Inventory-III",
        "ابزار ارزیابی الگوهای شخصیت بالینی و سندروم‌ها در ۲۱ مقیاس با ۱۷۵ گویه درست/نادرست؛ مناسب بالای ۱۴ سال و جمعیت بالینی.",
        "فردی", "بالای ۱۴ سال", 30, "#facc15", 3, "published",
        questions, interps,
    )


def build_both(seed: int = 20261021) -> list[dict]:
    rng = random.Random(seed)
    return [build_mmpi(rng), build_mcmi(rng)]
