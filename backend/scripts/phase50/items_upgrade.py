def build_scat27(rng: random.Random) -> dict:
    questions: list[dict] = []
    for sub, stems in SCAT:
        texts = expand(stems, SCAT_PREFIX, 3)
        for text in texts:
            questions.append(q(text + ".", "agree4", subscale=sub))
    assert len(questions) == 27, len(questions)
    rng.shuffle(questions)
    total_max = 27 * 3
    interps = bands(total_max, [
        (0.0, 0.3, "لنگرهای شغلی نامتمرکز", "هنوز لنگر غالب شکل نگرفته؛ تجربه‌های متنوع پیشنهاد می‌شود."),
        (0.3, 0.55, "لنگرهای شغلی در حال شکل‌گیری", "ترجیح‌ها روشن می‌شود؛ بازخورد با مشاور شغلی مفید است."),
        (0.55, 0.8, "لنگرهای شغلی مشخص", "لنگرهای غالب معلوم است؛ مسیر حرفه‌ای را با آن هم‌سو کنید."),
        (0.8, 1.0, "لنگرهای شغلی قوی", "هویت حرفه‌ای پایدار؛ تصمیم‌های شغلی را بر لنگر غالب بچینید."),
    ])
    return test(
        "schein-anchors", "SCAT-27", "آزمون لنگرهای مسیر شغلی شاین",
        "Schein's Career Anchors Test",
        "شناسایی لنگرهای هویت شغلی (فنی، مدیریتی، خودمختاری، امنیت، کارآفرینی، خدمت، چالش، سبک زندگی، پرشتاب) با ۲۷ گویه.",
        "شغلی", "نوجوان، بزرگسال", 10, "#4ade80", 17, "published",
        questions, interps,
    )


