def build_mbti(rng: random.Random) -> dict:
    questions: list[dict] = []
    for dim, pairs in MBTI_PAIRS.items():
        rng.shuffle(pairs)
        for a, b in pairs:
            questions.append(q("کدام گزینه به شما نزدیک‌تر است؟", [[a, 1], [b, 0]], subscale=dim))
    assert len(questions) == 88, len(questions)
    total_max = 22 * 4  # هر بُعد حداکثر ۲۲ در صورت گزینه اول
    interps = bands(total_max, [
        (0.0, 0.35, "الگوی درون‌گرا/حسی/احساسی/ادراکی غالب", "تمایل به درون‌گرایی، واقع‌گرایی، همدلی و انعطاف برجسته است؛ جلسه بازخورد نوع‌شناسی پیشنهاد می‌شود."),
        (0.35, 0.65, "الگوی ترکیبی متعادل", "نمره‌ها در مرز ابعاد است؛ تفسیر با مصاحبه تکمیلی دقیق‌تر می‌شود."),
        (0.65, 1.0, "الگوی برون‌گرا/شهودی/تفکری/داور غالب", "تمایل به برون‌گرایی، شهود، منطق و ساختار برجسته است؛ بازخورد شغلی نوع‌شناسی پیشنهاد می‌شود."),
    ])
    return test(
        "mbti-88", "MBTI-88", "تست شخصیت مایرز-بریگز",
        "Personality Test of Myers & Briggs",
        "نوع‌شناسی چهاربعدی شخصیت (E/I، S/N، T/F، J/P) با ۸۸ گویه انتخاب دوگانه؛ مناسب بالای ۱۷ سال برای خودشناسی و مشاوره شغلی.",
        "فردی", "بالای ۱۷ سال", 20, "#9333ea", 2, "published",
        questions, interps,
    )


