def build_neo(rng: random.Random) -> dict:
    questions: list[dict] = []
    for domain, facet, stems in NEO_FACETS:
        subs = f"{facet} ({domain})"
        texts: list[str] = []
        for s in stems:
            texts.append(s)
        for s in stems:
            texts.append(f"{NEO_PREFIX[len(texts) % len(NEO_PREFIX)]} {s}")
        for i, text in enumerate(texts[:8]):
            rev = (i % 3 == 2)
            questions.append(q(text, "agree5", subscale=subs, reverse=rev))
    assert len(questions) == 240, len(questions)
    rng.shuffle(questions)
    total_max = 240 * 4
    interps = bands(total_max, [
        (0.0, 0.3, "پروفایل پایین", "ویژگی‌های شخصیتی در محدوده آرام و بی‌تنش؛ تفسیر بر اساس ریزنمره ابعاد انجام شود."),
        (0.3, 0.55, "پروفایل متعادل", "توازن نسبی میان ابعاد پنج‌گانه شخصیت؛ جلسه بازخورد برای تفسیر ابعاد توصیه می‌شود."),
        (0.55, 0.78, "پروفایل فعال", "برخی ابعاد برجسته‌اند؛ بازخورد تخصصی و طراحی برنامه رشد فردی پیشنهاد می‌شود."),
        (0.78, 1.0, "پروفایل شدید", "شدت در ابعاد کلیدی مشهود است؛ مشاوره تخصصی شخصیت توصیه می‌شود."),
    ])
    return test(
        "neo-pi-r", "NEO-PI-R", "آزمون ویژگی‌های شخصیتی نئو",
        "Revised NEO Personality Inventory",
        "مدل پنج‌عاملی بزرگ شخصیت با ۳۰ زیروجه و ۲۴۰ گویه پنج‌درجه‌ای؛ نمره ابعاد نوروتیسم، برون‌گرایی، باز بودن، سازگاری و وجدان.",
        "فردی", "بالای ۱۰ سال", 40, "#4ade80", 4, "published",
        questions, interps,
    )


